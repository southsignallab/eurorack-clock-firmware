"""Generate the README header image from the KiCad-derived front-panel artwork.

Both the wordmark ("CLOCK" / "DIGITAL MASTER CLOCK") and the module on the right
are taken from docs/assets/front-panel/clock-front-panel.svg, so the header can
never show a different panel, lettering or logo than the hardware. No font is
needed; the eight gate traces are drawn from fixed, documented patterns.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARTWORK = ROOT / "docs" / "assets" / "front-panel" / "clock-front-panel.svg"
OUTPUT = ROOT / "docs" / "assets" / "clock-header.svg"

WIDTH, HEIGHT = 1280, 640
BACKGROUND = "#0074E3"
INK = "#FFFFFF"
WORDMARK_MAX_Y_MM = 13.5      # engraving above this line is the CLOCK wordmark
SUBTITLE_MAX_Y_MM = 17.0      # ... and up to here the DIGITAL MASTER CLOCK line

# Eight illustrative one-bar gate patterns (16 steps, 1 = gate high for that step).
PATTERNS = (
    "1000100010001000",
    "1010101010101010",
    "1001001001001000",
    "1000001000100000",
    "1111000011110000",
    "1001010010100100",
    "1000000010000000",
    "1110111011101110",
)


def f(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".")


def path_y_extent(d: str) -> tuple[float, float]:
    ys = [float(y) for y in re.findall(r"-?[\d.]+ (-?[\d.]+)", d)]
    return min(ys), max(ys)


def path_x_extent(d: str) -> tuple[float, float]:
    xs = [float(x) for x in re.findall(r"(-?[\d.]+) -?[\d.]+", d)]
    return min(xs), max(xs)


def generate() -> str:
    art = ARTWORK.read_text(encoding="utf-8")
    title = re.search(r"<title[^>]*>([^<]+)</title>", art).group(1)
    width_mm, height_mm = (float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', art).groups())
    body = re.search(r"(  <defs>.*?</g>)\n</svg>", art, re.S).group(1)
    engraving = re.findall(r'    <path d="([^"]+)"([^/]*)/>', art)

    wordmark = [(d, attrs) for d, attrs in engraving if path_y_extent(d)[1] <= WORDMARK_MAX_Y_MM]
    subtitle = [(d, attrs) for d, attrs in engraving
                if WORDMARK_MAX_Y_MM < path_y_extent(d)[1] <= SUBTITLE_MAX_Y_MM]
    if not wordmark or not subtitle:
        raise SystemExit("cannot locate the wordmark in the front-panel engraving")

    def bbox(items):
        xs = [v for d, _ in items for v in path_x_extent(d)]
        ys = [v for d, _ in items for v in path_y_extent(d)]
        return min(xs), min(ys), max(xs), max(ys)

    wx0, wy0, wx1, wy1 = bbox(wordmark)
    sx0, sy0, sx1, sy1 = bbox(subtitle)

    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" width="{WIDTH}" height="{HEIGHT}" '
        'role="img" aria-labelledby="header-title header-desc">',
        '  <title id="header-title">CLOCK - digital master clock by South Signal Lab</title>',
        f'  <desc id="header-desc">README header. Wordmark and module are the engraving of: {title}.</desc>',
        '  <!-- GENERATED by scripts/generate_readme_header.py from docs/assets/front-panel/clock-front-panel.svg. -->',
        f'  <rect width="{WIDTH}" height="{HEIGHT}" fill="{BACKGROUND}"/>',
    ]

    # Wordmark and subtitle, scaled from panel millimetres.
    left, word_w = 60.0, 700.0
    k = word_w / (wx1 - wx0)
    top = 70.0
    lines.append(f'  <g transform="translate({f(left - wx0 * k)} {f(top - wy0 * k)}) scale({f(k)})" '
                 f'fill="{INK}" stroke="{INK}" stroke-linecap="round" stroke-linejoin="round">')
    for d, attrs in wordmark:
        lines.append(f'    <path d="{d}"{attrs}/>')
    lines.append('  </g>')
    ks = word_w / (sx1 - sx0)
    sub_top = top + (wy1 - wy0) * k + 34.0
    lines.append(f'  <g transform="translate({f(left - sx0 * ks)} {f(sub_top - sy0 * ks)}) scale({f(ks)})" '
                 f'fill="{INK}" stroke="{INK}" stroke-linecap="round" stroke-linejoin="round">')
    for d, attrs in subtitle:
        lines.append(f'    <path d="{d}"{attrs}/>')
    lines.append('  </g>')

    # Gate traces.
    trace_top = sub_top + (sy1 - sy0) * ks + 60.0
    trace_h, trace_gap, trace_w = 14.0, 16.0, word_w
    step_w = trace_w / 16.0
    for row, pattern in enumerate(PATTERNS):
        base = trace_top + row * (trace_h + trace_gap) + trace_h
        d = [f"M{f(left)} {f(base)}"]
        level = False
        for i, bit in enumerate(pattern):
            x = left + i * step_w
            high = bit == "1"
            if high and level:                      # retrigger: short low notch before the next gate
                d.append(f"L{f(x - step_w * 0.12)} {f(base - trace_h)} L{f(x - step_w * 0.12)} {f(base)} "
                         f"L{f(x)} {f(base)} L{f(x)} {f(base - trace_h)}")
            elif high:
                d.append(f"L{f(x)} {f(base)} L{f(x)} {f(base - trace_h)}")
            elif level:
                d.append(f"L{f(x)} {f(base - trace_h)} L{f(x)} {f(base)}")
            level = high
        end = left + trace_w
        d.append(f"L{f(end)} {f(base - trace_h if level else base)}")
        lines.append(f'  <path d="{" ".join(d)}" fill="none" stroke="{INK}" stroke-width="2.4" '
                     'stroke-linejoin="round" stroke-linecap="round"/>')

    # Module on the right, at real proportions.
    panel_h = 580.0
    scale = panel_h / height_mm
    panel_w = width_mm * scale
    px = WIDTH - 60.0 - panel_w
    py = (HEIGHT - panel_h) / 2
    lines.append(f'  <rect x="{f(px + 6)}" y="{f(py + 8)}" width="{f(panel_w)}" height="{f(panel_h)}" '
                 'fill="#000000" fill-opacity="0.28"/>')
    # Cut-outs show the dark module interior rather than the page background.
    lines.append(f'  <rect x="{f(px)}" y="{f(py)}" width="{f(panel_w)}" height="{f(panel_h)}" fill="#050506"/>')
    lines.append(f'  <g transform="translate({f(px)} {f(py)}) scale({f(scale)})">')
    lines.append(body)
    lines.append('  </g>')
    lines.append('</svg>')
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    svg = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != svg:
            raise SystemExit(f"README header is stale: {OUTPUT}")
        return 0
    OUTPUT.write_text(svg, encoding="utf-8")
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
