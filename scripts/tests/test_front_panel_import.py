"""Regression tests for the KiCad front-panel importer and its committed outputs."""
from __future__ import annotations

import importlib.util
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("import_kicad_front_panel", ROOT / "scripts" / "import_kicad_front_panel.py")
importer = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = importer
SPEC.loader.exec_module(importer)

OX, OY = 100.0, 50.0  # arbitrary board offset; the importer must normalise to the panel corner


def circle(x: float, y: float, d: float, layer: str = "Edge.Cuts") -> str:
    return (f'\t(gr_circle (center {OX + x} {OY + y}) (end {OX + x + d / 2} {OY + y}) '
            f'(stroke (width 0.05) (type solid)) (fill none) (layer "{layer}") (uuid "c"))\n')


def rect_lines(x0: float, y0: float, x1: float, y1: float) -> str:
    pts = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    out = ""
    for i in range(4):
        a, b = pts[i], pts[(i + 1) % 4]
        out += (f'\t(gr_line (start {OX + a[0]} {OY + a[1]}) (end {OX + b[0]} {OY + b[1]}) '
                f'(stroke (width 0.05) (type solid)) (layer "Edge.Cuts") (uuid "l"))\n')
    return out


def synthetic_board(extra: str = "", drop_led: bool = False) -> str:
    body = rect_lines(0, 0, 50.5, 128.5)
    body += rect_lines(3.75, 22.25, 28.75, 35.85)                    # display window
    for sx, sy in ((6.47, 3.0), (42.03, 3.0), (6.47, 125.5), (42.03, 125.5)):
        body += rect_lines(sx - 1.7, sy - 1.7, sx + 3.7, sy + 1.7)   # mounting slots
    for x in (8.2, 25.12, 41.75):
        body += circle(x, 52.3, 9.2)
    body += circle(40.7, 29.25, 7.1)
    body += circle(7.75, 70.1, 6.0) + circle(19.4167, 70.13, 6.0)
    xs = (7.75, 19.4167, 31.0833, 42.75)
    for y in (88.93, 107.73):
        for x in xs:
            body += circle(x, y, 6.0)
    leds = [(x + 3.165, y - 7.37) for y in (88.93, 107.73) for x in xs]
    if drop_led:
        leds = leds[1:]
    for x, y in leds:
        body += circle(x, y, 3.1)
    body += (f'\t(gr_poly (pts (xy {OX + 10} {OY + 10}) (xy {OX + 20} {OY + 10}) (xy {OX + 20} {OY + 12})) '
             '(stroke (width 0) (type solid)) (fill yes) (layer "F.SilkS") (uuid "p"))\n')
    return "(kicad_pcb (version 20241229)\n" + body + extra + ")\n"


class FrontPanelImportTests(unittest.TestCase):
    def load(self, text: str):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "Panel.kicad_pcb"
            path.write_text(text, encoding="utf-8")
            (Path(tmp) / "Panel.kicad_pro").write_text('{"text_variables": {"HW_REV": "Z"}}', encoding="utf-8")
            return importer.load_panel(path)

    def test_classifies_controls_from_edge_cuts(self) -> None:
        panel = self.load(synthetic_board())
        self.assertEqual((panel.width, panel.height), (50.5, 128.5))
        self.assertEqual(panel.hw_rev, "Z")
        elements = importer.classify(panel)
        self.assertEqual([round(x, 2) for x, _ in elements["buttons"]], [8.2, 25.12, 41.75])
        self.assertEqual(elements["encoder"], (40.7, 29.25))
        self.assertEqual(elements["inputs"][0], (7.75, 70.1))
        self.assertEqual(len(elements["outputs"]), 8)
        self.assertLess(elements["outputs"][0][1], elements["outputs"][4][1])
        self.assertAlmostEqual(elements["display"][2], 25.0, places=3)
        self.assertAlmostEqual(elements["display"][3], 13.6, places=3)
        self.assertEqual(len(elements["screws"]), 4)

    def test_rejects_unexpected_hole_set(self) -> None:
        panel = self.load(synthetic_board(drop_led=True))
        with self.assertRaises(SystemExit):
            importer.classify(panel)

    def test_rejects_kicad_text_in_engraving(self) -> None:
        extra = '\t(gr_text "IN 1" (at 110 120) (layer "F.SilkS") (uuid "t"))\n'
        with self.assertRaises(SystemExit):
            self.load(synthetic_board(extra))

    def test_artwork_is_mm_based_and_clipped(self) -> None:
        svg = importer.artwork_svg(self.load(synthetic_board()))
        self.assertIn('viewBox="0 0 50.5 128.5"', svg)
        self.assertIn('fill-rule="evenodd"', svg)
        self.assertIn('clip-path="url(#panel-clip)"', svg)
        self.assertIn("HW_REV Z", svg)
        self.assertNotIn("<text", svg)


class CommittedFrontPanelTests(unittest.TestCase):
    def test_committed_outputs_carry_kicad_provenance(self) -> None:
        artwork = (ROOT / "docs/assets/front-panel/clock-front-panel.svg").read_text(encoding="utf-8")
        layout = (ROOT / "sim/panel_layout.ini").read_text(encoding="utf-8")
        self.assertIn('GENERATED by scripts/import_kicad_front_panel.py from "Simple Frontpanel.kicad_pcb"', artwork)
        self.assertIn("# Front-panel source: Simple Frontpanel.kicad_pcb", layout)
        self.assertTrue((ROOT / "docs/assets/front-panel/clock-front-panel.png").is_file())
        self.assertTrue((ROOT / "sim/panel_background.png").is_file())

    def test_derived_panel_files_are_current(self) -> None:
        for script in ("generate_front_panel_illustration.py", "generate_vcv_panel.py"):
            subprocess.run([sys.executable, str(ROOT / "scripts" / script), "--check"], cwd=ROOT, check=True)


if __name__ == "__main__":
    unittest.main()
