namespace clockfw::services {

/**
 * @brief Converts the two conditioned comparator inputs into configured musical roles.
 *
 * The physical PA8/PA9 paths remain the existing SYNC/RST hardware nets, but their
 * semantic roles are global firmware assignments. EXTI callbacks only enqueue
 * timestamped edges; all role interpretation and engine mutation happens at the
 * deterministic scheduler boundary.
 */
class ExternalSyncController final : public hal::FlashCommitGate {
  public:
    /**
     * @brief Binds the conditioned input capture to the clock engine.
     * @param inputCapture Edge queues and levels of the two comparator inputs; not owned.
     * @param engine Clock engine driven by the input roles; not owned.
     */
    ExternalSyncController(hal::ExternalInputCapture& inputCapture, engine::ClockEngine& engine);

    /**
     * @brief Initializes input interpretation from the persisted clock state.
     * @param state Configuration providing SYNC settings, input roles, BPM, tempo range
     *              and clock source.
     */
    void begin(const ClockState& state);
    /**
     * @brief Publishes changed input/timing configuration to scheduler context.
     *
     * Foreground only; the copy into the scheduler-side fields runs under one interrupt
     * lock. Unchanged configuration returns without taking the lock.
     * @param state Current configuration.
     */
    void updateConfiguration(const ClockState& state);
    /**
     * @brief Interprets queued comparator activity at one scheduler boundary.
     *
     * Order: role changes, RESET, START, RESTART, TAP, STOP, SYNC, RUN, inactive inputs,
     * then the lock timeout.
     * @param nowUs Current time in microseconds (wrapping 32-bit time base of the edge
     *              timestamps).
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void processSchedulerTick(std::uint32_t nowUs);
    /** @brief Clears estimator lock and returns to acquisition state. */
    void clearExternalLock();
    /**
     * @brief Returns the current filtered external tempo in milli-BPM.
     * @return Filtered tempo in milli-BPM; 0 before the first measured period.
     */
    std::uint32_t filteredBpmMilli() const;
    /**
     * @brief Records a front-panel transport action for external auto-start policy.
     *
     * Foreground only; runs under one interrupt lock. An assigned RUN input reacts only
     * to its next level change afterwards (D-03).
     * @param transport Transport state selected on the front panel.
     */
    void notifyManualTransportState(TransportState transport);
    /**
     * @brief Consumes one transport transition requested by an assigned input.
     *
     * Foreground only; runs under one interrupt lock.
     * @param transport Receives the requested state when true is returned.
     * @return True when a transition was pending.
     */
    bool consumeTransportTransition(TransportState& transport);

    /**
     * @brief Counts transport commands from the inputs: START, STOP, RESTART and RUN changes.
     *
     * These are the input events that count as user activity (E-11). SYNC pulses, lock
     * changes, RESET, TAP and inputs set to OFF do not change it. Written only by the
     * scheduler ISR; one aligned 32-bit read in the foreground.
     * @return Wrapping command counter.
     */
    std::uint32_t transportCommandSequence() const {
        return transportCommandSequence_;
    }

    /**
     * @brief Consumes one TAP request generated by an assigned external input.
     * @param timestampUs Receives the exact captured rising-edge timestamp in microseconds
     *                    when true is returned.
     * @return True when a TAP was pending.
     *
     * Foreground only; runs under one interrupt lock.
     */
    bool consumeTapRequest(std::uint32_t& timestampUs);

    /**
     * @brief Opens the Flash commit window only while the engine is stopped (D-04).
     *
     * Checked and set inside one interrupt lock, so no scheduler tick can start
     * the engine between the check and the erase. While open, RUN/START/RESTART
     * and AUTOSTART on lock are recorded instead of executed.
     * @return False while the engine is playing; the commit must then not run.
     */
    [[nodiscard]] bool tryOpenCommitWindow() override;

    /** @brief Closes the window and executes the latest deferred start, if any. */
    void closeCommitWindow() override;

#ifdef CLOCK_HOST_TEST
    /** @brief True while a start is recorded inside an open commit window. */
    bool startDeferredForTest() const {
        return deferredStart_;
    }
#endif

  private:
    /** Sentinel used when no input-driven transport transition is pending. */
    static constexpr std::uint8_t kNoPendingTransportTransition = 0xFFU;

    /**
     * @brief Starts the engine now, or records the start while a Flash commit runs.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void startOrDeferFromIsr();

    /**
     * @brief Stops the engine and drops a start recorded during a commit window.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void stopFromIsr();

    /**
     * @brief Closes the commit window and takes a deferred start; runs under the engine's lock.
     * @param context The controller.
     * @return True when a start was still deferred, so the engine starts.
     */
    static bool takeDeferredStartUnsafe(void* context);

    /**
     * @brief Processes the input assigned to RESET.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void processResetEdges();
    /**
     * @brief Processes the input assigned to SYNC.
     *
     * Rejects periods below the glitch floor, measures accepted periods, applies the
     * configured Q8 smoothing and updates lock and tempo in the engine.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void processSyncEdges();
    /**
     * @brief Processes one edge-triggered transport/input role.
     * @param function START, STOP, RESTART or TAP; other roles drain without effect.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void processTransportEdge(InputFunction function);
    /**
     * @brief Applies level-authoritative RUN semantics.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void processRunLevel();
    /**
     * @brief Discards activity for OFF and reserved roles.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void drainInactiveInputs();
    /**
     * @brief Applies role changes safely at scheduler boundary.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void applyInputConfiguration();

    /**
     * @brief Returns the physical input index assigned to a role, or -1.
     * @param function Role to look up.
     * @return 0 for input 1 (SYNC jack), 1 for input 2 (RST jack), -1 when unassigned.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    int assignedInput(InputFunction function) const;
    /**
     * @brief Pops one queued edge from a physical comparator input.
     * @param inputIndex 0 or 1; other values return false.
     * @param edge Receives the edge when true is returned.
     * @return True when an edge or an overflow marker was taken.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    bool popInputEdge(int inputIndex, hal::ExternalInputEdge& edge);
    /**
     * @brief Returns the conditioned current level of a physical input.
     * @param inputIndex 0 or 1; other values report false.
     * @return True when the conditioned input is high.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    bool inputLevelHigh(int inputIndex) const;
    /**
     * @brief Discards all queued edges from one physical input.
     * @param inputIndex 0 or 1; other values do nothing.
     * @isr TIM3 scheduler interrupt: bounded (at most kQueueCapacity pops per input queue;
     *      the EXTI producer cannot preempt TIM3), non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    void drainInput(int inputIndex);

    /**
     * @brief Returns whether a comparator level is the configured SYNC edge.
     * @param high Level after the edge.
     * @return True for a rising edge with SyncEdge::Rising, otherwise for a falling edge.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    bool selectedSyncEdge(bool high) const;
    /**
     * @brief Converts one accepted external period to milli-BPM.
     * @param periodUs Pulse period in microseconds.
     * @return Tempo in milli-BPM for the configured PPQN, capped at
     *         config::kSupportedMaximumBpm; 0 for a zero period.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    std::uint32_t calculateBpmMilli(std::uint32_t periodUs) const;
    /**
     * @brief Returns the adaptive external-clock timeout in microseconds.
     * @return The larger of the configured timeout and two filtered periods (or two
     *         periods at the minimum BPM before a period is known), saturated to 32 bits.
     * @isr TIM3 scheduler interrupt: constant time, non-blocking, no allocation, no output,
     *      opens no interrupt lock.
     */
    std::uint32_t effectiveTimeoutUs() const;
    /**
     * @brief Releases external lock and applies the configured loss policy.
     *
     * Also called from clearExternalLock() in the foreground under an interrupt lock.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void loseExternalLockFromIsr();
    /**
     * @brief Applies auto-start policy when a valid external lock is acquired.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void startOnLockAcquisitionFromIsr();
    /**
     * @brief Starts transport from an external role.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void requestPlayFromInput();
    /**
     * @brief Stops transport from an external role.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void requestStopFromInput();
    /**
     * @brief Performs deterministic stop-to-play restart from an external role.
     * @isr TIM3 scheduler interrupt: bounded, non-blocking, no allocation, no output, opens
     *      no interrupt lock; calls only ClockEngine ...FromIsr() functions.
     */
    void requestRestartFromInput();

    /** Comparator edge queues and levels; not owned. */
    hal::ExternalInputCapture& inputCapture_;
    /** Clock engine; not owned. */
    engine::ClockEngine& engine_;

    /** Foreground copy of the SYNC settings, compared in updateConfiguration(). */
    ExternalSyncSettings foregroundSettings_{};
    /** Foreground copy of the input roles. */
    ExternalInputAssignments foregroundInputs_{};
    /** Foreground copy of the fallback tempo in milli-BPM. */
    std::uint32_t foregroundFallbackBpmMilli_ = 120000U;
    /** Foreground copy of the minimum BPM (at least 1). */
    std::uint16_t foregroundMinimumBpm_ = 20U;
    /** Foreground copy of the clock source. */
    ClockSource foregroundSource_ = ClockSource::Auto;

    /** SYNC settings used in scheduler context. */
    ExternalSyncSettings settings_{};
    /** Input roles used in scheduler context. */
    ExternalInputAssignments inputs_{};
    /** Tempo in milli-BPM reported after a timing-role change. */
    std::uint32_t fallbackBpmMilli_ = 120000U;
    /** Minimum BPM (at least 1) for the timeout before a period is known. */
    std::uint16_t minimumBpm_ = 20U;
    /** Clock source used in scheduler context. */
    ClockSource source_ = ClockSource::Auto;

    /** True until applyInputConfiguration() applied the RESET gate state. */
    bool configurationDirty_ = false;
    /** True until applyInputConfiguration() drained both inputs after a role change. */
    bool inputRolesChanged_ = false;
    /** RESET gate level last sent to the engine. */
    bool resetGateApplied_ = false;
    /** True once runLevelApplied_ holds a reference level. */
    bool runLevelInitialized_ = false;
    /** RUN level last applied to transport. */
    bool runLevelApplied_ = false;

    /** True after the first selected SYNC edge has established a period reference. */
    bool haveReferencePulse_ = false;
    /** True while the SYNC estimator is locked. */
    bool externalLocked_ = false;
    /** Timestamp in microseconds of the last accepted SYNC edge. */
    std::uint32_t lastAcceptedPulseUs_ = 0U;
    /** Smoothed SYNC period in microseconds, Q8 fixed point; 0 when unknown. */
    std::uint64_t filteredPeriodQ8_ = 0U;
    /** Value returned by filteredBpmMilli(). */
    std::uint32_t filteredBpmMilli_ = 0U;

    /** True when lock acquisition may start and lock loss may stop transport. */
    bool autoTransportArmed_ = true;
    /** TransportState requested by an input for the foreground, or the sentinel. */
    volatile std::uint8_t pendingTransportTransition_ = kNoPendingTransportTransition;
    /** Value returned by transportCommandSequence(). */
    volatile std::uint32_t transportCommandSequence_ = 0U;
    /** True while a TAP from an input awaits consumeTapRequest(). */
    volatile bool pendingTap_ = false;
    /** True while a Flash commit window is open (D-04). */
    bool commitWindowOpen_ = false;
    /** True when a start was recorded inside the open commit window. */
    bool deferredStart_ = false;
    /** Timestamp in microseconds of the pending TAP edge. */
    volatile std::uint32_t pendingTapTimestampUs_ = 0U;
};

}  // namespace clockfw::services
